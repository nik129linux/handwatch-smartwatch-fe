#!/usr/bin/env node
/* Trains the gesture model and writes js/model-weights.js.
   node scripts/train-model.js   (from the prototype folder) */
const fs = require('fs');
const path = require('path');
const Model = require('../js/model.js');

const w = Model.trainFromSignal({ trainSeeds: { from: 100000 }, perScenario: 300 });
const out = '/* model-weights.js — generated by scripts/train-model.js, do not edit.\n' +
  '   Softmax regression, ' + w.meta.trainSize + ' synthetic streams, seeds ' +
  w.meta.trainSeeds.from + '-' + w.meta.trainSeeds.to + '. */\n' +
  'var ModelWeights = ' + JSON.stringify(w, null, 1) + ';\n' +
  "if (typeof module !== 'undefined' && module.exports) { module.exports = ModelWeights; }\n";
fs.writeFileSync(path.join(__dirname, '..', 'js', 'model-weights.js'), out);
const h = Model.heldOut({ noise: 0.35, perScenario: 40 });
console.log('held-out n=' + h.n + ' model=' + h.accuracy.toFixed(3) + ' rules=' + h.baseline.toFixed(3));
