#!/usr/bin/env node
/* Web build for the cloud demo (Cloudflare static assets).
   Copies the page as is and adds one bridge: window.__aiAPI, which the
   Electron preload provides on desktop. Here it calls the shared AWS server
   (/api/watch/query, Groq with Gemini fallback). The event log and the
   wrist push already fall back on their own in a plain browser.
   Output: web-dist/ (gitignored). The app key ships in the page, same as
   in the APK: it stops scanners, not someone reading the source. */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'web-dist');
const API_BASE = (process.env.WATCH_API_BASE || 'https://184-72-152-71.sslip.io').replace(/\/+$/, '');

function appKey() {
  if (process.env.WATCH_APP_KEY) return process.env.WATCH_APP_KEY;
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, 'ai', 'app-key.json'), 'utf8')).key || '';
  } catch (e) {
    return '';
  }
}

const BRIDGE = `/* Generated by scripts/build-web.js: browser stand-in for the Electron AI bridge. */
(function () {
  'use strict';
  if (window.__aiAPI) return;
  var BASE = ${JSON.stringify(API_BASE)};
  var KEY = ${JSON.stringify(appKey())};
  function call(path, opts, ms) {
    var ctrl = new AbortController();
    var timer = setTimeout(function () { ctrl.abort(); }, ms || 15000);
    opts = opts || {};
    opts.signal = ctrl.signal;
    opts.headers = Object.assign({ 'X-App-Key': KEY }, opts.headers || {});
    return fetch(BASE + path, opts).finally(function () { clearTimeout(timer); });
  }
  window.__aiAPI = {
    query: function (prompt) {
      return call('/api/watch/query', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt: String(prompt || '') })
      }).then(function (res) {
        return res.json().then(function (d) {
          if (!res.ok || !d || !d.ok || typeof d.text !== 'string') return { ok: false, reason: (d && d.reason) || 'down' };
          return { ok: true, text: d.text, model: d.model || 'server' };
        });
      }).catch(function () { return { ok: false, reason: 'down' }; });
    },
    health: function () {
      return call('/api/health', { method: 'GET' }, 8000)
        .then(function (res) { return res.ok ? { ok: true, model: 'server' } : { ok: false, reason: 'down' }; })
        .catch(function () { return { ok: false, reason: 'down' }; });
    }
  };
})();
`;

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    const s = path.join(src, name);
    const d = path.join(dst, name);
    if (fs.statSync(s).isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

fs.rmSync(OUT, { recursive: true, force: true });
for (const dir of ['css', 'js', 'fonts']) {
  if (fs.existsSync(path.join(ROOT, dir))) copyDir(path.join(ROOT, dir), path.join(OUT, dir));
}
fs.writeFileSync(path.join(OUT, 'js', 'web-bridge.js'), BRIDGE);

const TAG = '<script src="js/ai.js"></script>';
for (const page of ['index.html', 'unit.html']) {
  const src = path.join(ROOT, page);
  if (!fs.existsSync(src)) continue;
  let html = fs.readFileSync(src, 'utf8');
  if (html.includes(TAG)) html = html.replace(TAG, '<script src="js/web-bridge.js"></script>\n' + TAG);
  fs.writeFileSync(path.join(OUT, page), html);
}
if (!appKey()) console.warn('warning: no app key, the server will answer 401');
console.log('web build: ' + OUT);
